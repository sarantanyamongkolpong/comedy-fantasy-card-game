#!/usr/bin/env node
/**
 * Build the player-facing slice of content/v06/sport for the web client.
 *
 * Reads content/v06/sport/index.json and only the files it links.
 * Writes web/sport/live/content.public.json with parody fields only:
 * no `real` blocks, no source URLs, no snapshot dates, no internal notes.
 * Numbers keep their PROPOSED / BALANCE_PLACEHOLDER status.
 *
 *   node tools/sport-web/build-public-content.mjs          # write
 *   node tools/sport-web/build-public-content.mjs --check  # exit 1 if stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const repo = new URL('../../', import.meta.url);
const contentDir = new URL('content/v06/sport/', repo);
export const OUTPUT = new URL('web/sport/live/content.public.json', repo);

const SPORTS = ['football', 'basket', 'car', 'moto'];

function readJson(url) {
  return JSON.parse(readFileSync(url, 'utf8'));
}

function value(field) {
  if (field && typeof field === 'object' && 'value' in field) return field.value;
  return field;
}

function flatStats(stats, keys) {
  if (!stats) return null;
  const out = {};
  for (const key of keys) {
    const v = value(stats[key]);
    if (typeof v === 'number') out[key] = v;
  }
  return out;
}

/** "RB/RWB" -> primary "RB", roles ["RB","RWB"]. Coach "COA" -> "COACH". Race "entry" -> "ENTRY". */
function normalizeRole(raw) {
  if (raw === 'COA') return { role: 'COACH', roles: ['COACH'] };
  if (raw === 'entry') return { role: 'ENTRY', roles: ['ENTRY'] };
  const roles = String(raw).split('/').map((part) => part.trim()).filter(Boolean);
  return { role: roles[0], roles };
}

function publicCard(record, statKeys, teamIdByName) {
  const { role, roles } = normalizeRole(record.role);
  return {
    id: record.id,
    sport: record.sport,
    role,
    roles,
    roleLabel: record.role,
    parodyName: record.parodyName,
    rarity: record.rarity,
    team: record.team,
    teamId: teamIdByName.get(record.team) ?? null,
    bannerId: record.bannerId,
    stats: flatStats(record.stats, statKeys),
    vehicleId: record.vehicleId ?? null,
    vehicleName: record.vehicleParodyName ?? null,
    fictional: record.fictional === true,
    balance: 'BALANCE_PLACEHOLDER',
    status: 'PROPOSED',
    art: { slot: record.art?.slot ?? record.id, placeholder: true },
  };
}

function publicRow(record, extra = []) {
  const row = { id: record.id, parodyName: record.parodyName, status: 'PROPOSED', fictional: record.fictional === true };
  for (const key of ['summary', 'shape', 'venueId', 'vehicleId', 'entryIds', 'teamId', ...extra]) {
    if (record[key] !== undefined) row[key] = structuredClone(record[key]);
  }
  return row;
}

function flatten(node) {
  if (Array.isArray(node)) return node.map(flatten);
  if (node && typeof node === 'object') {
    if ('value' in node && ('balance' in node || 'status' in node)) return node.value;
    const out = {};
    for (const [key, child] of Object.entries(node)) {
      if (key === 'internalNote' || key === 'real') continue;
      out[key] = flatten(child);
    }
    return out;
  }
  return node;
}

export function buildPublicContent() {
  const index = readJson(new URL('index.json', contentDir));
  const file = (key) => readJson(new URL(index.files[key], contentDir));
  const tuning = readJson(new URL('tuning.json', contentDir));
  const out = {
    schemaVersion: 'sport-v0.6-web-public',
    sourceSchema: index.schemaVersion,
    contentTier: index.contentTier,
    status: 'PROPOSED',
    balance: 'BALANCE_PLACEHOLDER',
    note: 'Generated by tools/sport-web/build-public-content.mjs from content/v06/sport/index.json. Parody fields only. Do not edit by hand.',
    statKeys: index.statKeys,
    rarities: index.rarities,
    bannerIds: index.bannerIds,
    sports: {},
    tuning: {
      status: 'PROPOSED',
      balance: 'BALANCE_PLACEHOLDER',
      banners: flatten(tuning.banners),
      eventRewardsG: flatten(tuning.eventRewardsG),
      matchLengths: flatten(tuning.matchLengths),
      coachPassiveWeight: flatten(tuning.coachPassiveWeight),
    },
  };
  for (const sport of SPORTS) {
    const keys = index.statKeys[sport];
    const teams = file(`${sport}_teams`).teams;
    const teamIdByName = new Map(teams.map((team) => [team.parodyName, team.id]));
    const athletes = file(`${sport}_athletes`).athletes;
    const coaches = file(`${sport}_coaches`).coaches ?? [];
    const block = {
      cards: [...athletes, ...coaches].map((record) => publicCard(record, keys, teamIdByName)),
      teams: teams.map((team) => publicRow(team)),
    };
    if (sport === 'football' || sport === 'basket') block.venues = file(`${sport}_venues`).venues.map((row) => publicRow(row));
    if (sport === 'football') block.formations = file('football_formations').formations.map((row) => publicRow(row));
    if (sport === 'basket') block.schemes = file('basket_schemes').schemes.map((row) => publicRow(row));
    if (sport === 'car' || sport === 'moto') {
      block.vehicles = file(`${sport}_vehicles`).vehicles.map((row) => publicRow(row));
      block.tracks = file(`${sport}_tracks`).tracks.map((row) => publicRow(row));
      block.tactics = file(`${sport}_tactics`).tactics.map((row) => publicRow(row));
    }
    out.sports[sport] = block;
  }
  return out;
}

export function renderPublicContent() {
  return `${JSON.stringify(buildPublicContent(), null, 1)}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = renderPublicContent();
  if (process.argv.includes('--check')) {
    const current = readFileSync(OUTPUT, 'utf8');
    if (current !== text) {
      console.error('web/sport/live/content.public.json is stale. Run node tools/sport-web/build-public-content.mjs');
      process.exit(1);
    }
    console.log('content.public.json is current');
  } else {
    writeFileSync(OUTPUT, text);
    console.log(`wrote ${fileURLToPath(OUTPUT)} (${text.length} bytes)`);
  }
}
