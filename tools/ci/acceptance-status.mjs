import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { overallStatus, parseTap, renderNodeSection, upsertNodeSection } from './lib/acceptance-report.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const statusPath = join(root, 'docs', 'qa', 'v05', 'ACCEPTANCE_STATUS.md');
function collectTests(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) collectTests(full, out);
    else if (/\.test\.(js|mjs)$/.test(name)) out.push(full);
  }
  return out;
}

const files = [
  ...collectTests(join(root, 'tests', 'acceptance', 'v05')),
  ...collectTests(join(root, 'tests', 'e2e')),
  ...collectTests(join(root, 'tests', 'regression')),
];

const run = spawnSync(process.execPath, ['--test', '--test-reporter=tap', ...files], {
  cwd: root,
  encoding: 'utf8',
  env: {
    PATH: process.env.PATH,
    HOME: process.env.HOME,
    TMPDIR: process.env.TMPDIR,
    LANG: process.env.LANG || 'C.UTF-8',
  },
});

const output = `${run.stdout ?? ''}\n${run.stderr ?? ''}`;
const parsed = parseTap(output);
const status = overallStatus(parsed.summary);
const regression = parsed.tests.find((entry) => entry.name.startsWith('regression existing suite'));
const section = renderNodeSection({
  nodeVersion: process.version,
  status,
  summary: parsed.summary,
  tests: parsed.tests,
  nestedRegression: regression
    ? `Nested baseline suite: \`${regression.status}\` (\`${regression.name}\`).`
    : '',
});

const stamp = new Intl.DateTimeFormat('en-CA', {
  timeZone: 'Asia/Bangkok',
  dateStyle: 'medium',
  timeStyle: 'short',
}).format(new Date());

const intro = `# v0.5 acceptance status

Updated ${stamp} (Asia/Bangkok). Generated by \`npm run test:acceptance\`.

PASS is only used when that Node version has zero failures, zero todos, and zero skips. INCOMPLETE is not PASS. FAIL is not PASS. This report does not assign a ship status. Totals below are for this checkout. A local merge of the data and engine branches is in \`docs/qa/v05/INTEGRATION_LOG.md\` and is not pushed.

`;

const previous = existsSync(statusPath) ? readFileSync(statusPath, 'utf8') : intro;
const withoutIntro = previous.replace(/^# v0\.5 acceptance status[\s\S]*?(?=## Node\.js )/m, '');
const seeded = previous.includes('## Node.js ')
  ? `${intro}${withoutIntro.replace(/^\s+/, '')}`
  : `${intro}## Node.js ${process.version}\n\n${section}\n`;
const body = previous.includes('## Node.js ')
  ? upsertNodeSection(seeded, process.version, section)
  : seeded;

mkdirSync(dirname(statusPath), { recursive: true });
writeFileSync(statusPath, body.endsWith('\n') ? body : `${body}\n`);
process.stdout.write(output);
process.stdout.write(`\nAcceptance status: ${status} (Node.js ${process.version}). Wrote ${statusPath}\n`);

if (process.env.GITHUB_STEP_SUMMARY) {
  const prior = existsSync(process.env.GITHUB_STEP_SUMMARY) ? readFileSync(process.env.GITHUB_STEP_SUMMARY, 'utf8') : '';
  writeFileSync(process.env.GITHUB_STEP_SUMMARY, `${prior}\n## V05_ACCEPTANCE Node.js ${process.version}\n\n**Result: ${status}**\n\n`);
}

if (status === 'FAIL' || run.status !== 0) process.exit(1);
